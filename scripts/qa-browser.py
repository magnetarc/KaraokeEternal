"""Exercise only the seeded, loopback test instance. Requires Python Playwright + Edge."""
from pathlib import Path
import json
import re
from playwright.sync_api import sync_playwright, expect

BASE = 'http://127.0.0.1:8091'
OUT = Path(__file__).resolve().parents[1] / 'qa-artifacts'
OUT.mkdir(exist_ok=True)
checks = []

def passed(name):
    checks.append(name)
    print('PASS:', name, flush=True)

def sign_in(page, username='host', destination='/library'):
    page.goto(BASE + destination + '?roomId=1')
    expect(page).to_have_url(re.compile(r'/account\?.*redirect='))
    page.get_by_placeholder('Username or email').fill(username)
    page.get_by_placeholder('Password', exact=True).fill('preview-' + username + '-2026')
    page.get_by_role('button', name='Sign In', exact=True).click()
    expect(page).to_have_url(BASE + destination)

with sync_playwright() as p:
    browser = p.chromium.launch(channel='msedge', headless=True, args=['--autoplay-policy=no-user-gesture-required'])
    host = browser.new_context(viewport={'width':1440,'height':1000})
    assert host.request.get(BASE + '/api/instance').json() == {'isTest': True}, 'Refusing a non-test server'
    page = host.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.on('dialog', lambda dialog: dialog.accept())
    sign_in(page)
    expect(page.get_by_role('article')).to_have_count(12)
    passed('real sign-in, library and seeded queue load')
    expect(page.get_by_text('TEST LIBRARY', exact=False)).to_be_visible()
    search = page.get_by_role('searchbox', name='Search songs or artists')
    search.fill('velvet electric')
    expect(page.get_by_role('article')).to_have_count(1)
    expect(page.get_by_role('article')).to_contain_text('Electric Hearts')
    page.get_by_role('button', name='All songs', exact=False).click()
    page.get_by_label('Genre', exact=True).select_option('Country')
    page.get_by_label('Decade', exact=True).select_option('1990s')
    page.get_by_label('Language', exact=True).select_option('English')
    page.get_by_label('Voices', exact=True).select_option('Duet')
    page.get_by_label('Collection', exact=True).select_option('Better together')
    expect(page.get_by_role('article')).to_have_count(2)
    passed('combined artist/title search and all five category filters')
    search.fill('no-such-song-in-the-demo')
    expect(page.get_by_role('heading', name='No songs found')).to_be_visible()
    page.get_by_role('button', name='All songs', exact=False).click()
    page.get_by_role('button', name='Duets', exact=False).click()
    expect(page.get_by_role('article')).to_have_count(4)
    page.get_by_role('button', name='All songs', exact=False).click()
    page.get_by_role('button', name='Favourites', exact=False).click()
    expect(page.get_by_role('article')).to_have_count(2)
    page.get_by_role('button', name='Unfavourite After the Applause', exact=True).click()
    expect(page.get_by_role('article')).to_have_count(1)
    page.get_by_role('button', name='All songs', exact=False).click()
    page.get_by_role('button', name='Favourite After the Applause', exact=True).click()
    passed('empty results, duet shortcut and persisted favourites')
    page.get_by_role('link', name='Original search ↗', exact=True).click()
    page.get_by_placeholder('Search', exact=True).fill('Electric')
    expect(page.get_by_role('button', name=re.compile(r'Electric.*Hearts', re.S)).first).to_be_visible()
    page.get_by_role('link', name='Modern browser', exact=True).click()
    expect(page.get_by_role('article')).to_have_count(12)
    passed('original search remains usable alongside the modern browser')
    row = page.get_by_role('article', name='After the Applause by The Neon Hours', exact=True)
    row.get_by_role('button', name='Edit categories').click()
    dialog = page.get_by_role('dialog')
    dialog.get_by_label('Genre', exact=True).fill('Synthpop')
    dialog.get_by_label('Collections (separate with commas)', exact=True).fill('Party starters, Test collection')
    dialog.get_by_role('button', name='Save categories', exact=True).click()
    expect(dialog).not_to_be_visible()
    page.reload()
    expect(row).to_contain_text('Synthpop')
    expect(page.get_by_label('Collection', exact=True).locator('option', has_text='Test collection')).to_have_count(1)
    passed('host category editor persists changes across reload')
    # Restore sample metadata so the review library remains useful.
    assert host.request.put(BASE + '/api/song/1/categories', data={'genre':'Pop','language':'English','decade':'2020s','performance':'Solo','collections':['Party starters']}).ok
    assert host.request.put(BASE + '/api/song/1/categories', data={'decade':'1987'}).status == 400
    assert host.request.put(BASE + '/api/song/99999/categories', data={}).status == 404
    guest = browser.new_context(viewport={'width':390,'height':844}, is_mobile=True, has_touch=True)
    singer = guest.new_page()
    singer.on('pageerror', lambda error: errors.append(str(error)))
    singer.on('dialog', lambda dialog: dialog.accept())
    sign_in(singer, 'singer')
    expect(singer.get_by_role('button', name='Edit categories')).to_have_count(0)
    assert guest.request.put(BASE + '/api/song/1/categories', data={'genre':'bad'}).status == 403
    anonymous = browser.new_context()
    assert anonymous.request.put(BASE + '/api/song/1/categories', data={}).status == 403
    anonymous.close()
    passed('category API rejects anonymous, non-host, invalid and missing-song writes')
    singer.get_by_role('button', name='Browse categories', exact=False).click()
    singer.get_by_label('Language', exact=True).select_option('Mandarin')
    expect(singer.get_by_role('article')).to_have_count(1)
    singer.get_by_role('button', name='All songs', exact=False).click()
    singer.get_by_role('button', name='Browse categories', exact=False).click()
    passed('phone category disclosure and language filtering')
    singer.get_by_role('link', name='Queue', exact=True).click()
    expect(singer.get_by_role('button', name='Remove', exact=True)).to_have_count(1)
    expect(singer.get_by_role('button', name='Remove', exact=True)).to_be_in_viewport()
    singer.get_by_role('button', name='Remove', exact=True).click()
    expect(singer.get_by_text('Blue Sky Duet', exact=True)).to_have_count(0)
    singer.get_by_role('link', name='Library', exact=True).click()
    singer.get_by_role('button', name='Add Blue Sky Duet to queue', exact=True).click()
    expect(singer.get_by_role('article', name='Blue Sky Duet by June & Jasper').get_by_role('button', name='Add Blue Sky Duet to queue')).to_be_disabled()
    passed('phone queue navigation, visible own-song removal and add-to-queue')
    page.reload()
    expect(page.get_by_role('article')).to_have_count(12)
    page.screenshot(path=str(OUT / 'desktop-browser.png'))
    singer.locator('main').evaluate('(el) => el.scrollTop = 0')
    singer.screenshot(path=str(OUT / 'phone-browser.png'))
    assert not singer.evaluate('document.documentElement.scrollWidth > innerWidth')
    singer.get_by_role('link', name='Queue', exact=True).click()
    singer.screenshot(path=str(OUT / 'phone-queue.png'))
    passed('desktop and 390px phone layouts, labelled navigation, no horizontal overflow')
    player = host.new_page()
    player.on('pageerror', lambda error: errors.append(str(error)))
    player.goto(BASE + '/player')
    expect(player.get_by_role('button', name='Play', exact=True).first).to_be_visible()
    player.get_by_role('button', name='Play', exact=True).first.click()
    player.wait_for_function('document.querySelector("video")?.currentTime > 1')
    expect(page.get_by_role('button', name='Skip to next →', exact=True)).to_be_visible()
    now_title = page.get_by_role('complementary', name='Queue preview').locator('h3').first
    previous_title = now_title.inner_text()
    page.get_by_role('button', name='Skip to next →', exact=True).click()
    expect(now_title).not_to_have_text(previous_title)
    expect(page.get_by_role('complementary', name='Queue preview')).not_to_contain_text('READY TO SING')
    player.wait_for_function('document.querySelector("video")?.currentTime > 0.1')
    player.get_by_role('button', name='Pause', exact=True).click()
    assert player.locator('video').evaluate('(v) => v.paused')
    passed('original MP4 player advances time, browser skip and pause work')
    player.screenshot(path=str(OUT / 'test-player.png'))
    player.close()
    # Check the cold /player sign-in preserves its destination.
    cold = browser.new_context()
    cold_page = cold.new_page()
    sign_in(cold_page, destination='/player')
    expect(cold_page.locator('#player-fs-container')).to_be_visible()
    passed('cold player URL returns to player after login')
    cold.close()
    assert not errors, errors
    passed('no browser JavaScript errors')
    browser.close()

(OUT / 'browser-results.json').write_text(json.dumps({'checks': checks, 'passed': len(checks), 'errors': []}, indent=2))
